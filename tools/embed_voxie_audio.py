"""Bundle Voxie's MP3 clips as a compact flash asset plus a C++ index.

Usage:
    python tools/embed_voxie_audio.py "C:\\path\\to\\Voxie Audio Files"
"""
from pathlib import Path
import sys

CLIPS = (
    "Cute1", "Cute2", "No1", "No2", "No3", "Scared1", "Scared2",
    "Scared3", "Scared4", "Shy1", "Shy2", "Shy3", "Shy4",
    "Wakeup1", "Wakeup2", "Yes1", "Yes2",
)


def main():
    if len(sys.argv) != 2:
        raise SystemExit("Pass the folder containing the Voxie MP3 files.")
    source = Path(sys.argv[1])
    destination = Path("lib/VoxieAudio")
    destination.mkdir(parents=True, exist_ok=True)
    offset = 0
    entries = []
    with (destination / "AudioAssets.bin").open("wb") as bundle:
        for clip in CLIPS:
            data = (source / f"{clip}.mp3").read_bytes()
            bundle.write(data)
            entries.append((clip, offset, len(data)))
            offset += len(data)

    with (destination / "AudioAssets.h").open("w", encoding="ascii", newline="\n") as out:
        out.write("// Generated by tools/embed_voxie_audio.py. Do not edit by hand.\n")
        out.write("#pragma once\n#include <Arduino.h>\n\n")
        out.write("extern \"C\" const uint8_t VoxieAudioData[];\n\n")
        out.write("namespace VoxieAudioAssets {\nstruct Clip { size_t offset; size_t size; };\n")
        for clip, clip_offset, length in entries:
            out.write(f"constexpr Clip {clip} = {{{clip_offset}, {length}}};\n")
        out.write("} // namespace VoxieAudioAssets\n")


if __name__ == "__main__":
    main()
